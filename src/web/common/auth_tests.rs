use super::*;
use argon2::password_hash::phc::PasswordHash;

const OLD_DEFAULT_HASH: &str = "$argon2id$v=19$m=19456,t=2,p=1$AAECAwQFBgcICQoLDA0ODw$o5rxj2qLW7RnAP2nT/mNPyRA5JC0Q5bK8KjACPZidDE";
const OLD_OUTPUT_16_HASH: &str =
    "$argon2id$v=19$m=4096,t=3,p=2$EBESExQVFhcYGRobHB0eHw$AKV0wyoIUhVMWCV15dRQRw";
const OLD_OUTPUT_64_HASH: &str = "$argon2id$v=19$m=8192,t=1,p=4$ICEiIyQlJicoKSorLC0uLw$0JGBGL/cuPoLn2dj0aSj0N8duRPZMT2F4IewzVuT6lNCNCtchZ/fVIoXu3yus1yaE7CGqUciSv1TVSSB3BTacg";

#[test]
fn plaintext_password_verifies_only_the_right_password() {
    let auth = Auth::from_plaintext("correct horse").unwrap();
    assert!(auth.verify("correct horse"));
    assert!(!auth.verify("wrong"));
    assert!(!auth.verify(""));
}

#[test]
fn generated_password_hashes_use_argon2id_defaults_and_fresh_salts() {
    let first = Auth::from_plaintext("s3cret").unwrap();
    let second = Auth::from_plaintext("s3cret").unwrap();
    let parsed = PasswordHash::new(&first.phc).unwrap();

    assert_eq!(parsed.algorithm.as_str(), "argon2id");
    assert_eq!(parsed.version, Some(19));
    assert_eq!(parsed.params.get_decimal("m"), Some(19_456));
    assert_eq!(parsed.params.get_decimal("t"), Some(2));
    assert_eq!(parsed.params.get_decimal("p"), Some(1));
    assert_eq!(parsed.salt.as_ref().unwrap().as_ref().len(), 16);
    assert_eq!(parsed.hash.as_ref().unwrap().as_bytes().len(), 32);
    assert_ne!(parsed.salt, PasswordHash::new(&second.phc).unwrap().salt);
}

#[test]
fn hashes_from_argon2_053_remain_verifiable() {
    // Fixed legacy PHC values were generated by Argon2 0.5.3 with explicit salts.
    for (phc, password, memory, time, parallelism, output_len) in [
        (OLD_DEFAULT_HASH, "old-default-secret", 19_456, 2, 1, 32),
        (OLD_OUTPUT_16_HASH, "old-sixteen-secret", 4_096, 3, 2, 16),
        (OLD_OUTPUT_64_HASH, "old-sixty-four-secret", 8_192, 1, 4, 64),
    ] {
        let parsed = PasswordHash::new(phc).unwrap();
        assert_eq!(parsed.params.get_decimal("m"), Some(memory));
        assert_eq!(parsed.params.get_decimal("t"), Some(time));
        assert_eq!(parsed.params.get_decimal("p"), Some(parallelism));
        assert_eq!(parsed.salt.as_ref().unwrap().as_ref().len(), 16);
        assert_eq!(parsed.hash.as_ref().unwrap().as_bytes().len(), output_len);

        let auth = Auth::from_hashed(phc).unwrap();
        assert!(auth.verify(password));
        assert!(!auth.verify("wrong password"));
    }
}

#[test]
fn hashed_password_roundtrips_and_verifies() {
    let phc = Auth::from_plaintext("s3cret").unwrap().phc;
    let auth = Auth::from_hashed(&phc).unwrap();
    assert!(auth.verify("s3cret"));
    assert!(!auth.verify("nope"));
}

#[test]
fn from_hashed_rejects_garbage_and_verification_rejects_unknown_algorithms() {
    assert!(Auth::from_hashed("not-a-phc-string").is_err());

    let unsupported = "$scrypt$v=1$ln=14,r=8,p=1$YWJjZGVmZ2hpamts$YWJjZGVmZ2hpamts";
    let auth = Auth::from_hashed(unsupported).unwrap();
    assert!(!auth.verify("password"));
}

#[test]
fn rate_limiter_allows_two_per_minute_then_blocks() {
    let limiter = RateLimiter::new();
    let t0 = Instant::now();
    assert!(limiter.check_and_record(t0));
    assert!(limiter.check_and_record(t0 + Duration::from_secs(1)));
    assert!(!limiter.check_and_record(t0 + Duration::from_secs(2)));
}

#[test]
fn rate_limiter_recovers_after_a_minute() {
    let limiter = RateLimiter::new();
    let t0 = Instant::now();
    assert!(limiter.check_and_record(t0));
    assert!(limiter.check_and_record(t0 + Duration::from_secs(1)));
    assert!(!limiter.check_and_record(t0 + Duration::from_secs(5)));
    assert!(limiter.check_and_record(t0 + Duration::from_secs(61)));
}

#[test]
fn rate_limiter_enforces_hourly_cap() {
    let limiter = RateLimiter::new();
    let t0 = Instant::now();
    for i in 0..MAX_PER_HOUR {
        let ok = limiter.check_and_record(t0 + Duration::from_secs((i as u64) * 40));
        assert!(ok, "attempt {i} within the hourly cap should pass");
    }
    let blocked = limiter.check_and_record(t0 + Duration::from_secs((MAX_PER_HOUR as u64) * 40));
    assert!(!blocked, "the 15th attempt in an hour is blocked");
}

#[test]
fn rejected_login_flood_keeps_bounded_history() {
    let limiter = RateLimiter::new();
    let t0 = Instant::now();
    let allowed = (0..4_000)
        .map(|i| limiter.check_and_record(t0 + Duration::from_secs(i)))
        .last()
        .unwrap();

    let attempts = limiter.attempts.lock().unwrap();
    assert!(!allowed, "a continuing flood must remain rate-limited");
    assert_eq!(attempts.len(), MAX_PER_HOUR);
}
